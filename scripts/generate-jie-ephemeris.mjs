import { readFile, writeFile } from "node:fs/promises";
import { SearchSunLongitude } from "astronomy-engine";

const dataStartYear = 1599;
const dataEndYear = 2101;
const verifiedStartYear = 1600;
const verifiedEndYear = 2100;
const longitudes = [285, 315, 345, 15, 45, 75, 105, 135, 165, 195, 225, 255];
const target = new URL("../src/jie-ephemeris.generated.ts", import.meta.url);
const rows = [];

for (let year = dataStartYear; year <= dataEndYear; year++) {
  const row = longitudes.map((longitude, month) => {
    const crossing = SearchSunLongitude(
      longitude,
      new Date(Date.UTC(year, month, 1)),
      10,
    );
    if (!crossing) throw new Error(`Không tìm thấy Jie ${year}/${month + 1}`);
    return Math.round(crossing.date.getTime() / 60000);
  });
  rows.push(row);
}

const content = `// Generated by scripts/generate-jie-ephemeris.mjs. Do not edit manually.
export const JIE_EPHEMERIS_DATA_START_YEAR=${dataStartYear};
export const JIE_EPHEMERIS_DATA_END_YEAR=${dataEndYear};
export const JIE_EPHEMERIS_VERIFIED_START_YEAR=${verifiedStartYear};
export const JIE_EPHEMERIS_VERIFIED_END_YEAR=${verifiedEndYear};
export const JIE_EPHEMERIS_LONGITUDES=[${longitudes.join(",")}] as const;
export const JIE_EPHEMERIS_UNIX_MINUTES=[
${rows.map((row) => `  ${row.join(",")},`).join("\n")}
] as const;
export const JIE_EPHEMERIS_PROVENANCE={
  source:"Astronomy Engine SearchSunLongitude",
  sourceUrl:"https://github.com/cosinekitty/astronomy",
  sourceVersion:"2.1.19",
  algorithm:"VSOP87-based apparent geocentric ecliptic longitude search",
  generatedAt:"2026-07-26",
  resolution:"nearest minute",
  verifiedRange:[${verifiedStartYear},${verifiedEndYear}] as const
} as const;
`;

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8");
  if (current !== content) throw new Error("Jie ephemeris artifact drift");
  console.log(JSON.stringify({ ephemerisTableStable: true, years: rows.length, boundaries: rows.length * 12 }));
} else {
  await writeFile(target, content);
  console.log(JSON.stringify({ ephemerisTableGenerated: true, years: rows.length, boundaries: rows.length * 12 }));
}
